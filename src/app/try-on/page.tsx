import type { Metadata } from "next";
import { redirect } from "next/navigation";
import { ArrowLeft, CircleAlert, Cpu, ShieldCheck, Sparkles } from "lucide-react";
import Link from "next/link";
import { TryOnWorkspace } from "@/components/try-on-workspace";
import type { TryOnProductOption } from "@/components/try-on-workspace";
import { getCatalogData } from "@/lib/catalog.server";
import { isSupabaseAdminConfigured } from "@/lib/supabase/admin";
import { isSupabaseConfigured } from "@/lib/supabase/config";
import { createSupabaseServerClient } from "@/lib/supabase/server";

export const metadata: Metadata = {
  title: "AI Studio",
  description: "TRYVORA's AI try-on studio for consenting adult members.",
};

export const dynamic = "force-dynamic";

type TryOnPageProps = {
  searchParams: Promise<{ product?: string }>;
};

export default async function TryOnPage({ searchParams }: TryOnPageProps) {
  const { product: requestedSlug } = await searchParams;
  const enabled =
    process.env.TRYVORA_AI_TRYON_ENABLED === "true" &&
    Boolean(process.env.FASHN_API_KEY?.trim()) &&
    isSupabaseConfigured() &&
    isSupabaseAdminConfigured();

  if (!isSupabaseConfigured()) {
    return (
      <UnavailableStudio
        message="AI try-on is not available yet. Configure a Supabase project and complete the private-photo setup before enabling it."
      />
    );
  }

  const supabase = await createSupabaseServerClient();
  const { data: claimsData, error: claimsError } = await supabase.auth.getClaims();
  if (claimsError || typeof claimsData?.claims?.sub !== "string") {
    redirect("/login");
  }

  if (!enabled) {
    return (
      <UnavailableStudio
        message="AI try-on is not enabled for this deployment. The FASHN API key and explicit server-side feature flag are required; no image will be sent while disabled."
      />
    );
  }

  const catalog = await getCatalogData();
  if (catalog.mode === "error") {
    return (
      <UnavailableStudio
        message="The live catalogue could not be loaded. No sample item will be sent for try-on."
      />
    );
  }

  const products: TryOnProductOption[] =
    catalog.mode === "database"
      ? catalog.products
          .filter((product) => !product.isSample && product.tryOnEligible === true)
          .map(({ slug, name, brand, category, categorySlug, image, imageAlt }) => ({
            slug,
            name,
            brand,
            category,
            categorySlug,
            image,
            imageAlt,
          }))
      : [];
  const selectedProduct = products.find((product) => product.slug === requestedSlug);

  return (
    <div className="page-wrap studio-wrap">
      <Link
        className="back-link"
        href={selectedProduct ? `/products/${selectedProduct.slug}` : "/explore"}
      >
        <ArrowLeft size={15} /> {selectedProduct ? "Back to piece" : "Back to the edit"}
      </Link>
      <section className="studio-workspace">
        <div className="studio-mark"><Sparkles size={22} /></div>
        <span className="eyebrow">TRYVORA AI STUDIO · EARLY ACCESS</span>
        <h1>A more personal<br /><em>kind of fitting.</em></h1>
        <div className="availability-banner">
          <CircleAlert size={18} />
          <span>
            <strong>AI-generated previews are estimates, not fit or size guarantees.</strong>
            <br />
            One result per request, generated by FASHN Virtual Try-On v1.6.
          </span>
        </div>
        <div className="studio-assurances">
          <span><Cpu size={15} /> FASHN v1.6 · 1 credit per result</span>
          <span><ShieldCheck size={15} /> No result images saved to TRYVORA</span>
        </div>
        <TryOnWorkspace
          initialProductSlug={selectedProduct?.slug}
          products={products}
        />
      </section>
    </div>
  );
}

function UnavailableStudio({ message }: { message: string }) {
  return (
    <div className="page-wrap studio-wrap">
      <Link className="back-link" href="/explore">
        <ArrowLeft size={15} /> Back to the edit
      </Link>
      <section className="studio-unavailable">
        <div className="studio-mark"><Sparkles size={22} /></div>
        <span className="eyebrow">TRYVORA AI STUDIO</span>
        <h1>A more personal<br /><em>kind of fitting.</em></h1>
        <div className="availability-banner">
          <CircleAlert size={18} />
          <span>
            <strong>AI try-on is unavailable.</strong>
            <br />
            {message}
          </span>
        </div>
        <p className="studio-description">
          We never create, display, or imply an AI result unless the configured inference service
          returns an actual image.
        </p>
        <div className="studio-assurances">
          <span><Cpu size={15} /> No fabricated results</span>
          <span><ShieldCheck size={15} /> Your photo stays private until you consent</span>
        </div>
        <Link className="button button-dark" href="/explore">Continue exploring</Link>
      </section>
    </div>
  );
}
